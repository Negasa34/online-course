module.exports = modules.map(({ topic, ...module }) => {
  const available = new Map(module.lessons.map((lesson) => [lesson._spec.slug, lesson._spec]));
  const lessonPlan = curriculum[module.slug];
  return {
    slug: module.slug,
    title: module.title,
    summary: module.summary,
    objectives: module.objectives,
    lessons: lessonPlan.map(([source, slug, title, patch = {}]) => {
      const base = available.get(source);
      if (!base) throw new Error(`Missing lesson source ${source} in ${module.slug}`);
      const overrides = curatedOverrides[module.slug][slug] || {};
      return makeLesson({ ...base, ...overrides, ...patch, slug, title }, 0, topic);
    })
  };
});
